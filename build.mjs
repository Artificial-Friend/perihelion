// Build: simulation core (wasm, embedded) + TypeScript -> one JS bundle, page + textures -> dist/
// The core is compiled from core/*.cpp when that source is present; otherwise the vendored
// assets/core.wasm (recovered from the last published build) is used as-is.
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import * as esbuild from 'esbuild';

const root = path.dirname(new URL(import.meta.url).pathname);
const dist = path.join(root, 'dist');
fs.mkdirSync(path.join(dist, 'tex'), { recursive: true });

let wasm;
if (fs.existsSync(path.join(root, 'core/build.sh'))) {
  execSync('sh core/build.sh', { cwd: root, stdio: 'inherit' });
  wasm = fs.readFileSync(path.join(root, 'build/core.wasm'));
} else wasm = fs.readFileSync(path.join(root, 'assets/core.wasm'));
fs.writeFileSync(path.join(root, 'src/sim/core_wasm.ts'), '// generated by build.mjs — do not edit\nexport const CORE_WASM_B64 = "' + wasm.toString('base64') + '";\n');

const dev = process.argv.includes('--dev');
await esbuild.build({
  entryPoints: [path.join(root, 'src/main.ts')], bundle: true, format: 'esm', target: 'es2022',
  outfile: path.join(dist, 'game.js'), minify: !dev, sourcemap: false, legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' }, logLevel: 'warning',
});

const css = fs.readFileSync(path.join(root, 'src/ui/style.css'), 'utf8');
const html = fs.readFileSync(path.join(root, 'src/ui/shell.html'), 'utf8').replace('/*CSS*/', css);
fs.writeFileSync(path.join(dist, 'index.html'), html);
for (const f of fs.readdirSync(path.join(root, 'assets/tex'))) fs.copyFileSync(path.join(root, 'assets/tex', f), path.join(dist, 'tex', f));

// Source bundle published next to the game, so the code survives workspace resets.
const files = {};
const walk = (d) => { for (const f of fs.readdirSync(path.join(root, d))) { const p = path.join(d, f); if (fs.statSync(path.join(root, p)).isDirectory()) walk(p); else if (!p.endsWith('core_wasm.ts')) files[p] = fs.readFileSync(path.join(root, p), 'utf8'); } };
for (const d of ['src', 'test']) if (fs.existsSync(path.join(root, d))) walk(d);
for (const f of ['build.mjs', 'package.json', 'tsconfig.json']) if (fs.existsSync(path.join(root, f))) files[f] = fs.readFileSync(path.join(root, f), 'utf8');
fs.writeFileSync(path.join(dist, 'source.json'), JSON.stringify({ note: 'PERIHELION source. Restore each key to its path; assets/core.wasm = base64 below.', coreWasmB64: wasm.toString('base64'), files }));

const kb = (f) => (fs.statSync(path.join(dist, f)).size / 1024).toFixed(0) + ' KB';
console.log('dist/index.html', kb('index.html'), '· game.js', kb('game.js'), '· source.json', kb('source.json'));
